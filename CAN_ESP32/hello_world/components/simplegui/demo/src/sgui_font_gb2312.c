/*------------------------------- Public --------------------------------*/
/* Map a character code to its glyph index. Sorted binary search on the table. */
SGUI_INT SGUI_GB2312_GetCharIndex(SGUI_UINT32 uiCode)
{
    SGUI_INT iLeft = 0;
    SGUI_INT iRight = (SGUI_INT)(sizeof(s_astrMap)/sizeof(s_astrMap[0])) - 1;

    /* Return a GLYPH INDEX, not a byte address: SimpleGUI multiplies it by
     * SGUI_USED_BYTE(iHeight) * iHalfWidth (= 12) itself. */
    if((uiCode > 0x19) && (uiCode < 0x7F))
    {
        return (SGUI_INT)(uiCode - 0x20);
    }
    while(iLeft <= iRight)
    {
        SGUI_INT iMid = (iLeft + iRight) / 2;
        if(s_astrMap[iMid].uiCode == (SGUI_UINT16)uiCode)
        {
            return (SGUI_INT)(s_astrMap[iMid].usOffset / 12);
        }
        else if(s_astrMap[iMid].uiCode < (SGUI_UINT16)uiCode)
        {
            iLeft = iMid + 1;
        }
        else
        {
            iRight = iMid - 1;
        }
    }
    return SGUI_INVALID_INDEX;
}

/* Copy glyph bytes. sStartAddr is a byte address computed by SimpleGUI. */
SGUI_SIZE SGUI_GB2312_GetFontData(SGUI_SIZE sStartAddr, SGUI_BYTE* pDataBuffer, SGUI_SIZE sReadSize)
{
    SGUI_SIZE sCount;

    sCount = 0;
    if(NULL != pDataBuffer)
    {
        for(sCount = 0; sCount < sReadSize; sCount++)
        {
            pDataBuffer[sCount] = s_aucGlyphs[sStartAddr + sCount];
        }
    }
    return sCount;
}

/* Advance one character: <0x80 is single width, >=0x80 starts a two-byte pair. */
SGUI_CSZSTR SGUI_GB2312_StepNext(SGUI_CSZSTR cszSrc, SGUI_UINT32* puiCode)
{
    const SGUI_CHAR* pcNext = cszSrc;

    if(NULL == pcNext)
    {
        return NULL;
    }
    *puiCode = (SGUI_UINT32)(SGUI_UINT8)pcNext[0];
    if(*puiCode < 0x80)
    {
        pcNext += 1;
    }
    else
    {
        *puiCode = (*puiCode << 8) | (SGUI_UINT32)(SGUI_UINT8)pcNext[1];
        pcNext += 2;
    }
    return (SGUI_CSZSTR)pcNext;
}

/* Full width for anything that is not ASCII. */
SGUI_BOOL SGUI_GB2312_IsFullWidth(SGUI_UINT32 uiCode)
{
    return (uiCode < 0x80) ? SGUI_FALSE : SGUI_TRUE;
}

