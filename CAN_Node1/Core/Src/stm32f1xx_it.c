/**
  * @brief CAN1 RX0 中断（收到的帧落在 FIFO0）。
  *
  * ⚠️ 这个函数**必须存在**，否则一切看起来都正常、但一个 CAN 帧都收不到：
  *   - 启动文件里 USB_LP_CAN1_RX0_IRQHandler 是 **weak** 空实现（死循环），
  *     链接不会报错；
  *   - NVIC 使能与 CAN_IT_RX_FIFO0_MSG_PENDING 通知都在 node1_bsp.c 里做了，
  *     所以"配置全对、就是收不到帧"具有很强的迷惑性。
  *
  * HAL_CAN_IRQHandler() 内部会清除中断标志并回调
  * HAL_CAN_RxFifo0MsgPendingCallback()（由 node1_bsp.c 提供，负责把帧搬进队列）。
  */
void USB_LP_CAN1_RX0_IRQHandler(void)
{
  extern CAN_HandleTypeDef hcan1;
  HAL_CAN_IRQHandler(&hcan1);
}

